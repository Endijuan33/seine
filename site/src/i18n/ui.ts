const CATALOGS: Record<Locale, Record<UiKey, string>> = { en, 'zh-Hans': zhHans, 'zh-Hant': zhHant };

// `astro build` doesn't type-check, so enforce matching keys here; a gap fails the build.
for (const [code, catalog] of Object.entries(CATALOGS)) {
    const missing = Object.keys(en).filter((k) => !catalog[k as UiKey]);
    const extra = Object.keys(catalog).filter((k) => !(k in en));
    if (missing.length || extra.length) {
        throw new Error(`ui.ts ${code}: missing [${missing.join(', ')}] extra [${extra.join(', ')}]`);
    }
}

export function useTranslations(locale: Locale) {
    const catalog = CATALOGS[locale];
    return (key: UiKey, vars: Record<string, string | number> = {}) =>
        catalog[key].replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}
