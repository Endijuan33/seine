#!/usr/bin/env python3
"""Regenerates src/backend/nvidia/blake2b_faraday.ptx, the BLAKE2b kernel built
for the Faraday header layout, which Seine loads through the driver when NVRTC
is not installed.

Usage: scripts/gen_blake2b_ptx.py <path to libnvrtc.so.12 from CUDA 12.0>

Use NVRTC 12.0 (for example the nvidia-cuda-nvrtc-cu12==12.0.76 wheel): the PTX
ISA it emits loads on every CUDA 12 and 13 driver. The header line records the
kernel source hash that a unit test compares against blake2b_kernel.cu.
"""
import ctypes
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KERNEL = ROOT / "src/backend/nvidia/blake2b_kernel.cu"
OUTPUT = ROOT / "src/backend/nvidia/blake2b_faraday.ptx"
# Faraday header layout (156-byte header base, 8-byte nonce): the final block
# holds 36 bytes, the nonce starts 4 bytes into message word 3, and round-0
# columns 0 and 3 carry no nonce bytes. Must match FARADAY_SHAPE in blake2b.rs.
DEFINES = [
    "-DSEINE_B2_NONCE_WORD=3",
    "-DSEINE_B2_NONCE_SHIFT=32",
    "-DSEINE_B2_MSG_WORDS=5",
    "-DSEINE_B2_PRE_COLUMNS=9",
]
OPTIONS = ["--std=c++14", "--restrict", *DEFINES, "--gpu-architecture=compute_52"]


def check(lib, result, program=None):
    if result == 0:
        return
    message = lib.nvrtcGetErrorString(result).decode()
    if program is not None:
        size = ctypes.c_size_t()
        lib.nvrtcGetProgramLogSize(program, ctypes.byref(size))
        log = ctypes.create_string_buffer(size.value)
        lib.nvrtcGetProgramLog(program, log)
        message += "\n" + log.value.decode(errors="replace")
    sys.exit(f"nvrtc failed: {message}")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    lib = ctypes.CDLL(sys.argv[1])
    lib.nvrtcGetErrorString.restype = ctypes.c_char_p
    major, minor = ctypes.c_int(), ctypes.c_int()
    check(lib, lib.nvrtcVersion(ctypes.byref(major), ctypes.byref(minor)))
    source = KERNEL.read_bytes()
    program = ctypes.c_void_p()
    check(lib, lib.nvrtcCreateProgram(ctypes.byref(program), source, b"seine_blake2b_pow.cu", 0, None, None))
    options = (ctypes.c_char_p * len(OPTIONS))(*[o.encode() for o in OPTIONS])
    check(lib, lib.nvrtcCompileProgram(program, len(OPTIONS), options), program)
    size = ctypes.c_size_t()
    check(lib, lib.nvrtcGetPTXSize(program, ctypes.byref(size)))
    ptx = ctypes.create_string_buffer(size.value)
    check(lib, lib.nvrtcGetPTX(program, ptx))
    lib.nvrtcDestroyProgram(ctypes.byref(program))
    digest = hashlib.sha256(source).hexdigest()
    header = (
        f"// Generated by scripts/gen_blake2b_ptx.py with NVRTC {major.value}.{minor.value}; do not edit.\n"
        f"// kernel-sha256: {digest}\n"
        f"// options: {' '.join(OPTIONS)}\n"
    )
    OUTPUT.write_text(header + ptx.value.decode())
    print(f"wrote {OUTPUT.relative_to(ROOT)} (NVRTC {major.value}.{minor.value}, kernel {digest[:12]})")


if __name__ == "__main__":
    main()
